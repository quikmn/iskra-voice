// Vendors Bergamot (the translation engine of Firefox Translations, MPL-2.0) into client/vendor/bergamot from the
// npm release @browsermt/bergamot-translator, pinned by version and the registry's SHA-512:
//   bergamot-translator.wasm  the engine, unchanged
//   bergamot-translator.js    its Emscripten glue, unchanged except for an ES module wrapper (so a module worker
//                             can load it without eval) and one line that ES modules' strict mode needs
//   LICENSE                   MPL-2.0 (the package's own license; the source is github.com/browsermt/bergamot-translator)
// Run it only to change the version: node scripts/vendor-bergamot.mjs
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync } from 'node:zlib'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const VERSION = '0.4.9'
const TARBALL = `https://registry.npmjs.org/@browsermt/bergamot-translator/-/bergamot-translator-${VERSION}.tgz`
const INTEGRITY = 'sha512-bNuuCwM/JnsIYQCKXcYKFT4Qc5vLMoB8Nbvz8ReIgs7xzebK8Sa+R8iEK8mLvNBe/WaZ6zrPaUQilLsRT/ea8Q=='
const LICENSE = 'https://raw.githubusercontent.com/browsermt/bergamot-translator/8cc5d0495479c9ec56eafafd6bcd7fb5b929ca98/LICENSE'
const LICENSE_SHA256 = '1f256ecad192880510e84ad60474eab7589218784b9a50bc7ceee34c2b91f1d5'
const OUT = join(ROOT, 'client/vendor/bergamot')

const response = await fetch(TARBALL)
if (!response.ok) throw new Error(`${TARBALL}: ${response.status}`)
const tgz = Buffer.from(await response.arrayBuffer())
const integrity = `sha512-${createHash('sha512').update(tgz).digest('base64')}`
if (integrity !== INTEGRITY) throw new Error(`integrity ${integrity}, expected ${INTEGRITY}`)

/** The files in a tar archive (plain ustar, as npm packs them). */
function untar(tar) {
  const files = new Map()
  for (let o = 0; o + 512 <= tar.length;) {
    const header = tar.subarray(o, o + 512)
    if (header.every((b) => b === 0)) break
    const text = (from, to) => header.subarray(from, to).toString('utf8').replace(/\0.*$/s, '')
    const name = [text(345, 500), text(0, 100)].filter(Boolean).join('/')
    const size = parseInt(text(124, 136).trim() || '0', 8)
    files.set(name, tar.subarray(o + 512, o + 512 + size))
    o += 512 + Math.ceil(size / 512) * 512
  }
  return files
}

const files = untar(gunzipSync(tgz))
const get = (name) => {
  const data = files.get(`package/${name}`)
  if (!data) throw new Error(`${name} isn't in the package`)
  return data
}

const glue = get('worker/bergamot-translator-worker.js').toString('utf8')
const strictFix = ['var global_object = this;', 'var global_object = globalThis;']
if (!glue.includes(strictFix[0])) throw new Error('the glue changed: check the strict-mode fix')
const wrapped = `// Bergamot translator ${VERSION} (https://github.com/browsermt/bergamot-translator), MPL-2.0: see LICENSE.
// Generated by scripts/vendor-bergamot.mjs from @browsermt/bergamot-translator/worker/bergamot-translator-worker.js:
// the Emscripten glue as it is, inside a function that takes the Module settings, plus one strict-mode fix.
/* eslint-disable */
// @ts-nocheck
export default function loadBergamot(Module) {
${glue.replace(strictFix[0], strictFix[1])}
return Module
}
`

mkdirSync(OUT, { recursive: true })
writeFileSync(join(OUT, 'bergamot-translator.js'), wrapped)
writeFileSync(join(OUT, 'bergamot-translator.wasm'), get('worker/bergamot-translator-worker.wasm'))
// The npm package has no license file: the repository's, at the commit the package was built from.
const license = Buffer.from(await (await fetch(LICENSE)).arrayBuffer())
if (createHash('sha256').update(license).digest('hex') !== LICENSE_SHA256) throw new Error('LICENSE changed')
writeFileSync(join(OUT, 'LICENSE'), license)
console.log(`Bergamot ${VERSION} is in ${OUT}`)
