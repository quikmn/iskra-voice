#!/usr/bin/env bash
# Rebuilds client/vendor/deepfilternet/ (DeepFilterNet3 noise suppression as WebAssembly) from source.
# Only needed to change versions: the result is committed. Needs git, curl, a Rust toolchain (rustup) with the
# wasm32-unknown-unknown target, and Node. Works in Git Bash on Windows, Linux and macOS.
#   scripts/build-deepfilter.sh [work dir]      (default: a temporary directory)
# Pinned: DeepFilterNet (libDF, MIT OR Apache-2.0) at its last commit, moved to tract 0.23.3 by
# client/vendor/deepfilternet/tract-0.23.patch (tract 0.23 runs the model about twice as fast in WebAssembly as the
# 0.21 in DeepFilterNet's own lockfile), every crate pinned by client/vendor/deepfilternet/Cargo.lock;
# wasm-bindgen 0.2.129, binaryen version_131. The model is the official DeepFilterNet3_onnx.tar.gz from the same commit.
set -euo pipefail
commit=d375b2d8309e0935d165700c91da9de862a99c31
bindgen=0.2.129
binaryen=version_131
model_sha=c94d91f70911001c946e0fabb4aa9adc37045f45a03b56008cb0c8244cb63616

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/client/vendor/deepfilternet"
work="${1:-$(mktemp -d)}"
mkdir -p "$work" "$out"
cd "$work"

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
case "$(uname -s)-$(uname -m)" in
  MINGW* | MSYS* | CYGWIN*) triple=x86_64-pc-windows-msvc; bin_os=x86_64-windows; exe=.exe ;;
  Linux-x86_64) triple=x86_64-unknown-linux-musl; bin_os=x86_64-linux; exe= ;;
  Darwin-arm64) triple=aarch64-apple-darwin; bin_os=arm64-macos; exe= ;;
  Darwin-x86_64) triple=x86_64-apple-darwin; bin_os=x86_64-macos; exe= ;;
  *) echo "unsupported host" >&2; exit 1 ;;
esac

if [ ! -d DeepFilterNet ]; then git clone --quiet https://github.com/Rikorose/DeepFilterNet.git; fi
git -C DeepFilterNet -c advice.detachedHead=false checkout --quiet "$commit"
git -C DeepFilterNet checkout --quiet -- .
git -C DeepFilterNet apply "$out/tract-0.23.patch"
cp "$out/Cargo.lock" DeepFilterNet/Cargo.lock

(cd DeepFilterNet && RUSTFLAGS="-C target-feature=+simd128" CARGO_TARGET_DIR="$work/target" \
  cargo build --locked --release -p deep_filter --lib --target wasm32-unknown-unknown --no-default-features --features wasm)

[ -x "wasm-bindgen-$bindgen-$triple/wasm-bindgen$exe" ] || \
  curl -sSfL "https://github.com/wasm-bindgen/wasm-bindgen/releases/download/$bindgen/wasm-bindgen-$bindgen-$triple.tar.gz" | tar xz
[ -x "binaryen-$binaryen/bin/wasm-opt$exe" ] || \
  curl -sSfL "https://github.com/WebAssembly/binaryen/releases/download/$binaryen/binaryen-$binaryen-$bin_os.tar.gz" | tar xz

rm -rf pkg
"./wasm-bindgen-$bindgen-$triple/wasm-bindgen$exe" --target web --out-dir pkg --out-name df "target/wasm32-unknown-unknown/release/df.wasm"
"./binaryen-$binaryen/bin/wasm-opt$exe" -O3 --all-features pkg/df_bg.wasm -o "$out/deepfilter.wasm"

# The generated JS, made safe for an AudioWorklet under the app's CSP: worklets have no TextDecoder (it's only used
# for error messages), and the module is always passed in (no fetching by itself, no import.meta).
node - pkg/df.js "$out/deepfilter.js" <<'EOF'
const fs = require('node:fs')
const [src, dst] = process.argv.slice(2)
let js = fs.readFileSync(src, 'utf8')
const swap = (from, to) => {
  if (!js.includes(from)) throw new Error('glue changed, update build-deepfilter.sh: ' + from)
  js = js.split(from).join(to)
}
swap("module_or_path = new URL('df_bg.wasm', import.meta.url);", "throw new Error('pass the module');")
swap('/* @ts-self-types="./df.d.ts" */', '/* @ts-self-types="./deepfilter.d.ts" */')
if (/new Function|import\.meta|\beval\(/.test(js)) throw new Error('unexpected eval or import.meta left in the glue')
const prelude = "const TextDecoder = globalThis.TextDecoder ?? class { decode(b) { return b ? String.fromCharCode(...b) : '' } };\n"
fs.writeFileSync(dst, '// Generated by wasm-bindgen from DeepFilterNet libDF; patched by scripts/build-deepfilter.sh. Do not edit.\n' + prelude + js)
EOF
cp pkg/df.d.ts "$out/deepfilter.d.ts"

# Saved as .bin: web servers like to send .gz files "Content-Encoding: gzip", and then browsers unpack them.
curl -sSfL -o "$out/DeepFilterNet3_onnx.tar.gz.bin" "https://github.com/Rikorose/DeepFilterNet/raw/$commit/models/DeepFilterNet3_onnx.tar.gz"
[ "$(sha256 "$out/DeepFilterNet3_onnx.tar.gz.bin")" = "$model_sha" ] || { echo "model checksum mismatch" >&2; exit 1; }
cp DeepFilterNet/LICENSE-MIT DeepFilterNet/LICENSE-APACHE "$out/"
echo "deepfilter.wasm $(sha256 "$out/deepfilter.wasm")"
